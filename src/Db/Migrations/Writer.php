<?php

declare(strict_types=1);

namespace BrewPHP\Db\Migrations;

use BrewPHP\Core\Application;
use BrewPHP\Db\Fields\Field;
use BrewPHP\Db\Index;
use BrewPHP\Db\Migrations\Operations\Operation;

/**
 * Writes migrations as PHP files.
 *
 * Only plain values can be written: null, booleans, numbers, strings,
 * arrays, enum cases, fields and indexes. Strings are written with
 * var_export(), so no value can break out of its literal.
 */
final class Writer
{
    private const FIELDS_NAMESPACE = 'BrewPHP\\Db\\Fields\\';

    private const OPERATIONS_NAMESPACE = 'BrewPHP\\Db\\Migrations\\Operations\\';

    /** @var array<string, true> */
    private array $imports = [];

    /**
     * The PHP source of a migration file.
     *
     * @param list<string> $dependencies
     * @param list<Operation> $operations
     */
    public function write(array $operations, array $dependencies = [], bool $initial = false): string
    {
        $this->imports = ['BrewPHP\\Db\\Migrations\\Migration' => true];
        $body = [];
        foreach ($operations as $operation) {
            $body[] = str_repeat(' ', 12) . $this->operation($operation) . ',';
        }

        $class = [];
        if ($initial) {
            $class[] = '    public bool $initial = true;';
            $class[] = '';
        }
        if ($dependencies !== []) {
            $class[] = '    public array $dependencies = [';
            foreach ($dependencies as $dependency) {
                $class[] = '        ' . var_export($dependency, true) . ',';
            }
            $class[] = '    ];';
            $class[] = '';
        }
        $class[] = '    public function operations(): array';
        $class[] = '    {';
        if ($body === []) {
            $class[] = '        return [];';
        } else {
            $class[] = '        return [';
            array_push($class, ...$body);
            $class[] = '        ];';
        }
        $class[] = '    }';

        $imports = array_keys($this->imports);
        sort($imports);

        return implode("\n", [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            ...array_map(static fn (string $import): string => 'use ' . $import . ';', $imports),
            '',
            '// Generated by BrewPHP ' . Application::VERSION . ' on ' . date('Y-m-d H:i') . '.',
            '',
            'return new class () extends Migration {',
            ...$class,
            '};',
            '',
        ]);
    }

    /**
     * A value as PHP code, with fully qualified class names. Used for
     * comparisons as well as writing.
     */
    public static function export(mixed $value): string
    {
        return (new self())->value($value, 0, false);
    }

    private function operation(Operation $operation): string
    {
        $arguments = $operation->arguments();
        if ($arguments === null) {
            throw new MigrationError(sprintf('%s cannot be written to a migration file; write it by hand.', $operation::class));
        }
        $this->imports['BrewPHP\\Db\\Migrations\\Operations'] = true;
        $class = 'Operations\\' . substr($operation::class, strlen(self::OPERATIONS_NAMESPACE));

        return $this->call('new ' . $class, $arguments, 12);
    }

    /**
     * @param array<string, mixed> $arguments
     */
    private function call(string $callee, array $arguments, int $indent, bool $useImports = true): string
    {
        $parts = [];
        $multiline = false;
        foreach ($arguments as $name => $value) {
            $code = $this->value($value, $indent + 4, $useImports);
            $multiline = $multiline || str_contains($code, "\n");
            $parts[] = $name . ': ' . $code;
        }
        if (!$multiline) {
            return $callee . '(' . implode(', ', $parts) . ')';
        }
        $pad = str_repeat(' ', $indent + 4);

        return $callee . "(\n" . $pad . implode(",\n" . $pad, $parts) . ",\n" . str_repeat(' ', $indent) . ')';
    }

    private function value(mixed $value, int $indent, bool $useImports = true): string
    {
        return match (true) {
            $value === null => 'null',
            is_bool($value) => $value ? 'true' : 'false',
            is_int($value) => (string) $value,
            is_float($value) => var_export($value, true),
            is_string($value) => var_export($value, true),
            $value instanceof \UnitEnum => '\\' . $value::class . '::' . $value->name,
            $value instanceof Field => $this->field($value, $indent, $useImports),
            $value instanceof Index => $this->index($value, $indent, $useImports),
            is_array($value) => $this->array($value, $indent, $useImports),
            default => throw new MigrationError(sprintf(
                'Cannot write a %s to a migration file. Use plain values (strings, numbers, arrays, enums).',
                get_debug_type($value),
            )),
        };
    }

    private function field(Field $field, int $indent, bool $useImports): string
    {
        $deconstructed = $field->deconstructForMigration();
        $class = $deconstructed['class'];
        if ($useImports && str_starts_with($class, self::FIELDS_NAMESPACE)) {
            $this->imports['BrewPHP\\Db\\Fields'] = true;
            $class = 'Fields\\' . substr($class, strlen(self::FIELDS_NAMESPACE));
        } else {
            $class = '\\' . $class;
        }

        return $this->call('new ' . $class, $deconstructed['options'], $indent, $useImports);
    }

    private function index(Index $index, int $indent, bool $useImports): string
    {
        $arguments = ['fields' => $index->fields];
        if ($index->name !== null) {
            $arguments['name'] = $index->name;
        }
        if ($index->unique) {
            $arguments['unique'] = true;
        }
        if ($useImports) {
            $this->imports[Index::class] = true;
        }

        return $this->call('new ' . ($useImports ? 'Index' : '\\' . Index::class), $arguments, $indent, $useImports);
    }

    /**
     * @param array<mixed> $value
     */
    private function array(array $value, int $indent, bool $useImports): string
    {
        if ($value === []) {
            return '[]';
        }
        $isList = array_is_list($value);
        $items = [];
        $multiline = false;
        foreach ($value as $key => $item) {
            $code = $this->value($item, $indent + 4, $useImports);
            $multiline = $multiline || str_contains($code, "\n") || $item instanceof Field;
            $items[] = $isList ? $code : var_export($key, true) . ' => ' . $code;
        }
        if (!$multiline) {
            return '[' . implode(', ', $items) . ']';
        }
        $pad = str_repeat(' ', $indent + 4);

        return "[\n" . $pad . implode(",\n" . $pad, $items) . ",\n" . str_repeat(' ', $indent) . ']';
    }
}
