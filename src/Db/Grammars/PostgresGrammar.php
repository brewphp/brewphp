<?php

declare(strict_types=1);

namespace BrewPHP\Db\Grammars;

/**
 * PostgreSQL. New primary keys are read with INSERT ... RETURNING, and
 * case-insensitive matching uses ILIKE.
 */
class PostgresGrammar extends Grammar
{
    public function __construct()
    {
        $this->types = array_replace($this->types, [
            'json' => 'jsonb',
            'uuid' => 'uuid',
        ]);
    }

    public function name(): string
    {
        return 'pgsql';
    }

    public function autoIncrementColumn(bool $big): string
    {
        return ($big ? 'bigint' : 'integer') . ' NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY';
    }

    public function compileLike(string $column, string $kind, bool $caseInsensitive, string $value): array
    {
        if ($kind === 'exact' && $caseInsensitive) {
            return ['UPPER(' . $column . '::text) = UPPER(?)', $value];
        }

        // ::text lets the text lookups work on any column type, like Django.
        return [
            $column . '::text' . ($caseInsensitive ? ' ILIKE ?' : ' LIKE ?'),
            $this->likePattern($this->escapeLike($value), $kind),
        ];
    }

    public function supportsReturning(): bool
    {
        return true;
    }
}
