<?php

declare(strict_types=1);

namespace BrewPHP\Tests\Unit\Db;

use BrewPHP\Db\Grammars\MysqlGrammar;
use BrewPHP\Db\Grammars\PostgresGrammar;
use BrewPHP\Db\Grammars\SqliteGrammar;
use BrewPHP\Tests\Fixtures\Models\PostStatus;
use BrewPHP\Tests\TestCase;

final class GrammarTest extends TestCase
{
    public function testQuoting(): void
    {
        self::assertSame('"a""b"', (new SqliteGrammar())->quoteIdentifier('a"b'));
        self::assertSame('"t"."c"', (new PostgresGrammar())->quoteColumn('t', 'c'));
        self::assertSame('`t`.`c``x`', (new MysqlGrammar())->quoteColumn('t', 'c`x'));
    }

    public function testColumnTypes(): void
    {
        $sqlite = new SqliteGrammar();
        $mysql = new MysqlGrammar();
        $pgsql = new PostgresGrammar();

        self::assertSame(['varchar(20)', 'varchar(20)', 'varchar(20)'], [$sqlite->type('varchar', 20), $mysql->type('varchar', 20), $pgsql->type('varchar', 20)]);
        self::assertSame(['text', 'longtext', 'text'], [$sqlite->type('text'), $mysql->type('text'), $pgsql->type('text')]);
        self::assertSame(['bool', 'bool', 'boolean'], [$sqlite->type('boolean'), $mysql->type('boolean'), $pgsql->type('boolean')]);
        self::assertSame(['decimal(8, 2)', 'decimal(8, 2)', 'numeric(8, 2)'], [$sqlite->type('decimal', 8, 2), $mysql->type('decimal', 8, 2), $pgsql->type('decimal', 8, 2)]);
        self::assertSame(['datetime', 'datetime', 'timestamp'], [$sqlite->type('datetime'), $mysql->type('datetime'), $pgsql->type('datetime')]);
        self::assertSame(['real', 'double precision', 'double precision'], [$sqlite->type('float'), $mysql->type('float'), $pgsql->type('float')]);
        self::assertSame(['text', 'json', 'jsonb'], [$sqlite->type('json'), $mysql->type('json'), $pgsql->type('json')]);
        self::assertSame(['char(36)', 'char(36)', 'uuid'], [$sqlite->type('uuid'), $mysql->type('uuid'), $pgsql->type('uuid')]);

        self::assertSame('integer NOT NULL PRIMARY KEY AUTOINCREMENT', $sqlite->autoIncrementColumn(true));
        self::assertSame('bigint NOT NULL AUTO_INCREMENT PRIMARY KEY', $mysql->autoIncrementColumn(true));
        self::assertSame('integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY', $pgsql->autoIncrementColumn(false));

        $this->expectException(\InvalidArgumentException::class);
        $sqlite->type('blob');
    }

    public function testLimitAndOffset(): void
    {
        self::assertSame(' LIMIT 10 OFFSET 5', (new PostgresGrammar())->compileLimit(10, 5));
        self::assertSame(' OFFSET 5', (new PostgresGrammar())->compileLimit(null, 5));
        self::assertSame(' LIMIT -1 OFFSET 5', (new SqliteGrammar())->compileLimit(null, 5));
        self::assertSame(' LIMIT 18446744073709551615 OFFSET 5', (new MysqlGrammar())->compileLimit(null, 5));
        self::assertSame(' LIMIT 3', (new MysqlGrammar())->compileLimit(3, 0));
        self::assertSame('', (new SqliteGrammar())->compileLimit(null, 0));
    }

    public function testLikeLookups(): void
    {
        self::assertSame(['"t" GLOB ?', '*a[*]b[?]c[[]*'], (new SqliteGrammar())->compileLike('"t"', 'contains', false, 'a*b?c['));
        self::assertSame(["\"t\" LIKE ? ESCAPE '\\'", '50\\%\\_%'], (new SqliteGrammar())->compileLike('"t"', 'startswith', true, '50%_'));
        self::assertSame(['`t` LIKE BINARY ?', '%x'], (new MysqlGrammar())->compileLike('`t`', 'endswith', false, 'x'));
        self::assertSame(['`t` LIKE ?', 'a\\\\b'], (new MysqlGrammar())->compileLike('`t`', 'exact', true, 'a\\b'));
        self::assertSame(['"t"::text ILIKE ?', '%x%'], (new PostgresGrammar())->compileLike('"t"', 'contains', true, 'x'));
        self::assertSame(['"t"::text LIKE ?', 'x%'], (new PostgresGrammar())->compileLike('"t"', 'startswith', false, 'x'));
        self::assertSame(['UPPER("t"::text) = UPPER(?)', 'x'], (new PostgresGrammar())->compileLike('"t"', 'exact', true, 'x'));
    }

    public function testDateParts(): void
    {
        self::assertSame("CAST(strftime('%Y', \"d\") AS integer)", (new SqliteGrammar())->datePart('year', '"d"'));
        self::assertSame('MONTH(`d`)', (new MysqlGrammar())->datePart('month', '`d`'));
        self::assertSame('EXTRACT(DAY FROM "d")', (new PostgresGrammar())->datePart('day', '"d"'));

        $this->expectException(\InvalidArgumentException::class);
        (new PostgresGrammar())->datePart('week', '"d"');
    }

    public function testInsert(): void
    {
        self::assertSame('INSERT INTO "t" ("a", "b") VALUES (?, ?)', (new SqliteGrammar())->compileInsert('t', ['a', 'b'], 'id'));
        self::assertSame('INSERT INTO "t" ("a") VALUES (?) RETURNING "id"', (new PostgresGrammar())->compileInsert('t', ['a'], 'id'));
        self::assertSame('INSERT INTO "t" DEFAULT VALUES RETURNING "id"', (new PostgresGrammar())->compileInsert('t', [], 'id'));
        self::assertSame('INSERT INTO `t` () VALUES ()', (new MysqlGrammar())->compileInsert('t', [], 'id'));
        self::assertSame('INSERT INTO `t` (`a`) VALUES (?)', (new MysqlGrammar())->compileInsert('t', ['a'], 'id'));
    }

    public function testLiterals(): void
    {
        self::assertSame(['NULL', 'TRUE', '1', '0', '3', '1.5', "'it''s'", "'draft'", '\'{"a":1}\''], [
            (new PostgresGrammar())->literal(null),
            (new PostgresGrammar())->literal(true),
            (new SqliteGrammar())->literal(true),
            (new MysqlGrammar())->literal(false),
            (new MysqlGrammar())->literal(3),
            (new MysqlGrammar())->literal(1.5),
            (new SqliteGrammar())->literal("it's"),
            (new SqliteGrammar())->literal(PostStatus::Draft),
            (new SqliteGrammar())->literal(['a' => 1]),
        ]);
        self::assertSame("'a\\\\b'", (new MysqlGrammar())->literal('a\\b'));
    }

    public function testIndexNamesAreStableAndShort(): void
    {
        $grammar = new PostgresGrammar();
        $name = $grammar->indexName('blog_post', ['author_id'], 'fk');

        self::assertSame($name, $grammar->indexName('blog_post', ['author_id'], 'fk'));
        self::assertNotSame($name, $grammar->indexName('blog_post', ['author_id'], 'idx'));
        self::assertMatchesRegularExpression('/^blog_post_author_id_[0-9a-f]{8}_fk$/', $name);

        $long = $grammar->indexName(str_repeat('t', 80), [str_repeat('c', 80)], 'uniq');
        self::assertSame(63, strlen($long));
        self::assertSame(64, strlen((new MysqlGrammar())->indexName(str_repeat('t', 80), ['c'], 'idx')));
    }

    public function testCapabilities(): void
    {
        self::assertSame(['sqlite', 'mysql', 'pgsql'], [(new SqliteGrammar())->name(), (new MysqlGrammar())->name(), (new PostgresGrammar())->name()]);
        self::assertTrue((new PostgresGrammar())->supportsReturning());
        self::assertFalse((new SqliteGrammar())->supportsReturning());
        self::assertFalse((new MysqlGrammar())->supportsDdlTransactions());
        self::assertTrue((new SqliteGrammar())->supportsDdlTransactions());
        self::assertSame('', (new MysqlGrammar())->deferrable());
    }
}
